# src/agentic/engine/compaction.py
"""Context compaction for long ReAct sessions (above all the task agent): long,
many-step sessions accumulate new tool calls and results every round, and because the
COMPLETE history so far is re-sent on every LLM call (see AgentSession.build_messages),
the tokens actually consumed grow quadratically over many rounds - a single large tool
call (e.g. a file newly written via create_file) would otherwise be sent again on every
further round, even though it is long since done and on disk.

When needed, this module replaces the OLDER part of the history (everything except the
system prompt, the first assignment message and the last few ReAct rounds) with a
concise summary generated by a cheap LLM. Called by runner._run_turn after completed
ReAct rounds when agent.enable_context_compaction is set.
"""
import json

import litellm

from src.core.logging_config import logger
from src.schemas.agent_schema import AgentSession, MessageRole, SessionMessage
from src.schemas.llm_models import LLMModels

COMPACTION_SYSTEM_PROMPT = """You summarize the work history so far of an agent working autonomously on an
assignment (tool calls, results, intermediate states). Your summary REPLACES the original history in the
agent's context - it must be able to continue working afterwards without the original data.

Preserve every fact that could still be relevant to the REMAINING work:
- What has already been done concretely (e.g. which files were created/changed/moved, with what result)?
- Which vault paths were created or affected?
- Which important contents/facts were researched (briefly, but concretely - names, values, relationships)?
- Current state/progress, open points.

Leave out technical noise (raw tool-call syntax, complete file contents that have already been written and
are no longer needed). Write densely and in note form, not as prose narration. Reply with the summary
ONLY, without any preamble."""


def _round_start_indices(messages: list[SessionMessage]) -> list[int]:
    """In our protocol every ASSISTANT message starts a new ReAct round (a tool-call
    round or the final answer). Cuts may only be made at these indices, otherwise a
    tool result would be separated from its tool call."""
    return [i for i, m in enumerate(messages) if m.role == MessageRole.ASSISTANT]


def _format_for_compaction(messages: list[SessionMessage]) -> str:
    lines = []
    for m in messages:
        if m.role == MessageRole.ASSISTANT and m.tool_calls:
            calls = ", ".join(f"{tc.tool_name}({tc.arguments})" for tc in m.tool_calls)
            lines.append(f"[ASSISTANT calls] {calls}")
        elif m.role == MessageRole.TOOL:
            lines.append(f"[TOOL RESULT ({m.tool_name})] {m.content}")
        else:
            lines.append(f"[{m.role.value.upper()}] {m.content}")
    return "\n\n".join(lines)


def context_size_chars(session: AgentSession) -> int:
    """Size of the context actually sent. Important: for ASSISTANT messages with tool
    calls, the real payload (e.g. the complete new file content for create_file) sits in
    tool_calls[].arguments, NOT in .content - those must be counted too, otherwise the
    dominant cost driver in practice is systematically missed."""
    total = 0
    for m in session.messages:
        total += len(m.content or "")
        for tc in m.tool_calls:
            total += len(json.dumps(tc.arguments, ensure_ascii=False))
    return total


def maybe_compact(session: AgentSession, step: int, session_logger) -> None:
    """Checks whether the current context exceeds the agent's threshold and compacts it
    if so. A no-op when compaction is disabled, the context is still small enough, or
    there are not yet enough rounds for a safe cut. Failures while compacting are not
    fatal - the context then simply stays unchanged and the session continues normally."""
    agent = session.agent
    if not agent.enable_context_compaction:
        return

    before_chars = context_size_chars(session)
    if before_chars < agent.compaction_threshold_chars:
        return

    head = session.messages[:2]  # System prompt + first assignment message, always preserved
    rest = session.messages[2:]

    round_starts = _round_start_indices(rest)
    keep_rounds = agent.compaction_keep_recent_rounds
    if len(round_starts) <= keep_rounds:
        return  # not yet enough completed rounds for a safe cut

    cut_index = round_starts[-keep_rounds]
    to_compact, recent = rest[:cut_index], rest[cut_index:]
    if not to_compact:
        return

    transcript = _format_for_compaction(to_compact)

    try:
        response = litellm.completion(
            model=agent.compaction_model,
            messages=[
                {"role": "system", "content": COMPACTION_SYSTEM_PROMPT},
                {"role": "user", "content": transcript},
            ],
        )
        summary = (response.choices[0].message.content or "").strip()
    except Exception as e:
        logger.error(f"[Compaction] Summarization failed, context left unchanged: {e}")
        return

    if not summary:
        logger.warning("[Compaction] Received an empty summary, context left unchanged.")
        return

    summary_message = SessionMessage(
        role=MessageRole.USER,
        content=f"[Summary of the history so far, {len(to_compact)} messages compacted]\n\n{summary}",
    )
    session.messages = head + [summary_message] + recent
    after_chars = context_size_chars(session)

    logger.info(
        f"[Compaction] {agent.name}: compacted {len(to_compact)} messages "
        f"({before_chars} -> {after_chars} chars)."
    )
    session_logger.log_compaction(step, before_chars, after_chars, len(to_compact), summary)
