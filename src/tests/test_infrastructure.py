def test_fake_llm_routes_and_scripts(fake_llm: FakeLLM):
    fake_llm.register("TestEcho", "SYSTEM_PROMPT_ECHO")
    fake_llm.script("TestEcho", final({"reply": "ok"}))

    response = litellm.completion(
        messages=[
            {"role": "system", "content": "SYSTEM_PROMPT_ECHO: do something"},
            {"role": "user", "content": "hello"},
        ]
    )
    assert response.choices[0].message.content == '{"reply": "ok"}'
    assert len(fake_llm.calls_for("TestEcho")) == 1


def test_fake_llm_scripted_exception(fake_llm: FakeLLM):
    fake_llm.register("TestErr", "SYSTEM_PROMPT_ERR")
    fake_llm.script("TestErr", ValueError("custom-error"))

    with pytest.raises(ValueError, match="custom-error"):
        litellm.completion(
            messages=[
                {"role": "system", "content": "SYSTEM_PROMPT_ERR"},
            ]
        )


