def test_sync_threads_runs_background_task_synchronously(sync_threads, fake_llm: FakeLLM):
    # Script TaskAgent first call: tool call update_plan, second call: final
    fake_llm.script(
        "TaskAgent",
        tool_calls(("update_plan", {"task_id": "dummy", "steps": [{"step": "Step 1", "status": "done"}]})),
        final({"summary": "Fertig"}),
    )
    # The actual task_id is dynamically generated by start_background_task.
    # To handle task_id dynamically, let's use a callable or we can inspect job after.
    # Since fake_llm supports callable:
    def update_plan_callable(kwargs):
        # find task_id from user prompt if possible or from _jobs
        active_task_id = list(_jobs.keys())[-1]
        return tool_calls(("update_plan", {"task_id": active_task_id, "steps": [{"step": "Step 1", "status": "done"}]}))

    # Reset script for TaskAgent
    fake_llm._scripts["TaskAgent"].clear()
    fake_llm.script(
        "TaskAgent",
        update_plan_callable,
        final({"summary": "Aufgabe synchron erledigt."}),
    )

    msg = start_background_task("Test Synchronous Execution")
    assert "task_id:" in msg
    task_id = list(_jobs.keys())[-1]
    job = _jobs[task_id]
    assert job.status == "done"
    assert "Aufgabe synchron erledigt." in check_task_status(task_id)
